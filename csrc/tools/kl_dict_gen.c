/* kl_dict_gen -- write the compiled-in dictionary's table from cmudict.dict.
 *
 *   kl_dict_gen <cmudict.dict> <out.c>
 *
 * Run by CMake at build time; its output, kl_dict_data.c, lives in the build
 * tree and is never checked in. Every entry of the file goes in -- the
 * alternative pronunciations ("read(2)") and the keys that are not plain
 * words as well -- with the key upper-cased (the front end looks words up in
 * upper case) and each phone as one code character (kl_dict_symbols.c).
 *
 * It refuses, and fails the build, on anything it cannot place: a line with
 * no phones, a phone outside the 69 symbols, a key repeated after upper-casing,
 * a key holding a space. A dictionary that changes shape upstream should stop
 * the build, not lose entries quietly.
 *
 * Output: string chunks of at most 4,095 bytes (see kl_dict.c for why), one
 * "KEY CODES\n" entry per source line, never split across chunks; the index
 * of entry starts, chunk << 12 | offset; and the count.
 *
 * SPDX-License-Identifier: BSD-3-Clause
 * Copyright (c) 2026 Päiv Dengo
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "kl_dict.h"

#define CHUNK_MAX 4095

typedef struct {
    char *key;
    char *codes;
} entry;

static void die(const char *what, long line)
{
    if (line > 0)
        fprintf(stderr, "kl_dict_gen: line %ld: %s\n", line, what);
    else
        fprintf(stderr, "kl_dict_gen: %s\n", what);
    exit(1);
}

static char *dup_n(const char *s, size_t n)
{
    char *d = malloc(n + 1);
    if (!d)
        die("out of memory", 0);
    memcpy(d, s, n);
    d[n] = '\0';
    return d;
}

static int by_key(const void *a, const void *b)
{
    return strcmp(((const entry *)a)->key, ((const entry *)b)->key);
}

/* One entry as it goes into a literal: the key with ", \ and ? escaped, a
 * space, the codes (which never need escaping), \n. Returns the bytes it
 * stands for in the chunk. */
static size_t put_entry(FILE *f, const entry *e)
{
    const char *p;
    fputc('"', f);
    for (p = e->key; *p; p++) {
        if (*p == '"' || *p == '\\' || *p == '?')
            fputc('\\', f);
        fputc(*p, f);
    }
    fprintf(f, " %s\\n\"\n", e->codes);
    return strlen(e->key) + 1 + strlen(e->codes) + 1;
}

int main(int argc, char **argv)
{
    FILE *in, *out;
    static char line[4096];
    entry *es = NULL;
    size_t n = 0, cap = 0, i, chunk = 0, used = 0, total = 0;
    unsigned long *index;
    long lineno = 0;

    if (argc != 3) {
        fprintf(stderr, "usage: kl_dict_gen <cmudict.dict> <out.c>\n");
        return 2;
    }
    in = fopen(argv[1], "rb");
    if (!in)
        die("cannot read the dictionary", 0);

    while (fgets(line, sizeof line, in)) {
        char *p = line, *k, *hash;
        char codes[128];
        size_t kl, nc = 0;

        lineno++;
        line[strcspn(line, "\r\n")] = '\0';
        hash = strstr(line, " #");          /* "word  P1 P2 # place, danish" */
        if (hash)
            *hash = '\0';
        while (*p == ' ' || *p == '\t')
            p++;
        if (!*p)
            continue;

        k = p;
        while (*p && *p != ' ' && *p != '\t')
            p++;
        kl = (size_t)(p - k);
        for (;;) {
            char *s;
            int sym;
            while (*p == ' ' || *p == '\t')
                p++;
            if (!*p)
                break;
            s = p;
            while (*p && *p != ' ' && *p != '\t')
                p++;
            sym = kl_dict_symbol_index(s, (size_t)(p - s));
            if (sym < 0)
                die("a phone outside the 69 symbols", lineno);
            if (nc + 1 >= sizeof codes)
                die("an entry with too many phones", lineno);
            codes[nc++] = kl_dict_code_char(sym);
        }
        if (nc == 0)
            die("an entry with no phones", lineno);
        codes[nc] = '\0';

        if (n == cap) {
            cap = cap ? cap * 2 : 1024;
            es = realloc(es, cap * sizeof *es);
            if (!es)
                die("out of memory", 0);
        }
        es[n].key = dup_n(k, kl);
        for (i = 0; i < kl; i++)
            if (es[n].key[i] >= 'a' && es[n].key[i] <= 'z')
                es[n].key[i] = (char)(es[n].key[i] - 'a' + 'A');
        es[n].codes = dup_n(codes, nc);
        n++;
    }
    fclose(in);
    if (n == 0)
        die("no entries", 0);

    qsort(es, n, sizeof *es, by_key);
    for (i = 1; i < n; i++)
        if (strcmp(es[i - 1].key, es[i].key) == 0)
            die("a key repeated after upper-casing", 0);

    out = fopen(argv[2], "wb");
    index = malloc(n * sizeof *index);
    if (!out || !index)
        die("cannot write the table", 0);

    fprintf(out,
        "/* GENERATED by csrc/tools/kl_dict_gen.c from data/cmudict/cmudict.dict.\n"
        " * Do not edit, and do not check in: it is rebuilt with the library.\n"
        " *\n"
        " * The CMU Pronouncing Dictionary, copyright (C) 1993-2015 Carnegie Mellon\n"
        " * University, under the terms in data/cmudict/LICENSE. %lu entries. */\n\n"
        "#include <stddef.h>\n#include <stdint.h>\n\n", (unsigned long)n);

    /* The chunks, each a run of adjacent literals. */
    fprintf(out, "static const char c0[] =\n");
    for (i = 0; i < n; i++) {
        size_t bytes = strlen(es[i].key) + 1 + strlen(es[i].codes) + 1;
        if (bytes > CHUNK_MAX)
            die("an entry longer than a chunk", 0);
        if (used + bytes > CHUNK_MAX) {
            chunk++;
            used = 0;
            fprintf(out, ";\nstatic const char c%lu[] =\n", (unsigned long)chunk);
        }
        index[i] = (unsigned long)(chunk << 12 | used);
        used += put_entry(out, &es[i]);
        total += bytes;
    }
    fprintf(out, ";\n\nconst char *const kl_dict_chunks[] = {\n");
    for (i = 0; i <= chunk; i++)
        fprintf(out, "    c%lu,%s", (unsigned long)i, (i % 8 == 7 || i == chunk) ? "\n" : "");
    fprintf(out, "};\n\nconst uint32_t kl_dict_index[] = {\n");
    for (i = 0; i < n; i++)
        fprintf(out, "%s%lu,%s", i % 10 == 0 ? "    " : " ", index[i],
                (i % 10 == 9 || i == n - 1) ? "\n" : "");
    fprintf(out, "};\n\nconst size_t kl_dict_entries = %lu;\n", (unsigned long)n);
    if (fclose(out) != 0)
        die("cannot write the table", 0);

    printf("kl_dict_gen: %lu entries, %lu chunks, %lu bytes of entries\n",
           (unsigned long)n, (unsigned long)(chunk + 1), (unsigned long)total);
    return 0;
}
