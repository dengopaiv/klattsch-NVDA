#!/usr/bin/env node
// Capture Votraxxion's letter-to-sound output, so the lift can be held to it.
//
//   node tools/capture-text-nrl.mjs --votraxxion DIR [--cc COMPILER] [--cmu DIR]
//
// Pass 1 of csrc/kl_text.c is Votraxxion's src/ttv.c, stage one, lifted. The
// claim is that the lift changed no output. This builds a small driver around
// Votraxxion's own ttv.c -- #included whole, so its static to_arpabet() is
// reachable without editing a line of it -- runs it over the hand corpus and
// over every plain word of the CMU dictionary, and writes
// goldens/text-nrl.json:
//
//   corpus      every hand-corpus line and Votraxxion's ARPABET for it, whole
//   cmu         a SHA-256 over the ARPABET of all the dictionary's words, one
//               per line, and the word count -- the dictionary is not ours to
//               check in, a digest of what a program made from its headwords
//               carries none of it
//   votraxxion  the commit the capture was made from
//
// Votraxxion is a sibling repository on the development machine, not a
// dependency, so this runs by hand and its output is checked in. What runs
// in CI is tools/verify-text.mjs, against that file.

import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { corpusLines, cmuWords } from './text-inputs.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const opt = (name) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
};

const vx = opt('--votraxxion');
if (!vx) {
  console.error('usage: capture-text-nrl.mjs --votraxxion DIR [--cc CC] [--cmu DIR]');
  process.exit(2);
}
const cc = opt('--cc') || process.env.CC || 'gcc';
const src = join(resolve(vx), 'src');
const commit = spawnSync('git', ['-C', resolve(vx), 'rev-parse', 'HEAD'])
  .stdout.toString().trim();
const dirty = spawnSync('git', ['-C', resolve(vx), 'status', '--porcelain', '--', 'src'])
  .stdout.toString().trim();
if (dirty) {
  console.error(`Votraxxion's src/ has uncommitted changes; capture from a commit:\n${dirty}`);
  process.exit(1);
}

const work = mkdtempSync(join(tmpdir(), 'kl-nrl-'));
const driver = join(work, 'nrl_driver.c');
writeFileSync(driver, `/* Generated by tools/capture-text-nrl.mjs. */
#include <stdio.h>
#include <string.h>
#ifdef _WIN32
#include <io.h>
#include <fcntl.h>
#endif
#include "${join(src, 'ttv.c').replace(/\\/g, '/')}"

int main(void)
{
    static ttv_ctx x;
    static char line[65536];
#ifdef _WIN32
    _setmode(_fileno(stdin), _O_BINARY);
    _setmode(_fileno(stdout), _O_BINARY);
#endif
    while (fgets(line, sizeof line, stdin)) {
        size_t n = strlen(line);
        if (n && line[n - 1] == '\\n') line[--n] = '\\0';
        if (n && line[n - 1] == '\\r') line[--n] = '\\0';
        to_arpabet(&x, line, (int)n);
        fputs(x.arpa, stdout);
        fputc('\\n', stdout);
    }
    return 0;
}
`);
const exe = join(work, process.platform === 'win32' ? 'nrl_driver.exe' : 'nrl_driver');
const build = spawnSync(cc, ['-O2', '-std=c17', '-I', src, driver,
                             join(src, 'ttv_tables.c'), '-o', exe]);
if (build.status !== 0) {
  console.error(`building the driver failed:\n${build.stderr}`);
  process.exit(1);
}

function run(lines) {
  const r = spawnSync(exe, [], { input: lines.join('\n') + '\n', maxBuffer: 1 << 30 });
  if (r.status !== 0) throw new Error(`driver failed: ${r.stderr}`);
  return r.stdout.toString('utf8').split('\n').slice(0, lines.length);
}

const corpus = corpusLines();
const corpusOut = run(corpus);
const cmu = await cmuWords(opt('--cmu'));
if (!cmu) {
  console.error('cmu-pronouncing-dictionary not found; pass --cmu DIR');
  process.exit(1);
}
const cmuOut = run(cmu.words);

const golden = {
  note: 'Votraxxion src/ttv.c to_arpabet() output. Written by ' +
        'tools/capture-text-nrl.mjs; checked by tools/verify-text.mjs.',
  votraxxion: commit,
  corpus: corpus.map((input, i) => [input, corpusOut[i]]),
  cmu: {
    dictionary: `cmu-pronouncing-dictionary ${cmu.version}`,
    words: cmu.words.length,
    sha256: createHash('sha256').update(cmuOut.join('\n') + '\n').digest('hex'),
  },
};
writeFileSync(join(root, 'goldens', 'text-nrl.json'), JSON.stringify(golden, null, 2) + '\n');
console.log(`captured ${corpus.length} corpus lines and ${cmu.words.length} words ` +
            `from Votraxxion ${commit.slice(0, 7)}`);
